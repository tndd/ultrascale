const {test,expect}=require('playwright/test');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
test('比較画像・倍率・左右交換・未検証表示',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve('build/quality-lab/index.html')).href);
  await expect(page.locator('#processing')).toHaveText('処理検証：PASS');
  await expect(page.getByText('見やすさ：未判定',{exact:true})).toBeVisible();
  await expect(page.getByText('合成・実モニタ：未検証',{exact:true})).toBeVisible();
  for(const id of ['imageA','imageB'])await expect.poll(()=>page.locator('#'+id).evaluate(img=>img.complete&&img.naturalWidth>0)).toBe(true);
  await page.getByLabel('比較A').selectOption('cubic');
  await page.getByLabel('比較B').selectOption('lanczos');
  await page.getByRole('button',{name:'4倍で画素を確認'}).click();
  await expect(page.locator('#imageA')).toHaveJSProperty('width',3840);
  await expect(page.locator('#imageA')).toHaveAttribute('src','cubic.png');
  await page.getByRole('button',{name:'左右を入れ替える'}).click();
  await expect(page.getByLabel('比較A')).toHaveValue('lanczos');
  await expect(page.getByLabel('比較B')).toHaveValue('cubic');
  await page.locator('#viewA').hover();await page.mouse.wheel(200,100);
  await expect.poll(async()=>{const a=await page.locator('#viewA').evaluate(e=>[e.scrollLeft,e.scrollTop]);const b=await page.locator('#viewB').evaluate(e=>[e.scrollLeft,e.scrollTop]);return JSON.stringify(a)===JSON.stringify(b)&&a[1]>0}).toBe(true);
  await page.screenshot({path:'build/quality-lab/report-zoom.png',fullPage:true});
  await page.getByRole('button',{name:'1倍表示'}).click();
  await expect(page.locator('#imageA')).toHaveJSProperty('width',960);
  for(const id of ['viewA','viewB'])await expect.poll(()=>page.locator('#'+id).evaluate(e=>[e.scrollLeft,e.scrollTop])).toEqual([0,0]);
  await expect(page.locator('#metrics tr')).toHaveCount(5);
  await page.screenshot({path:'build/quality-lab/report-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'build/quality-lab/report-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
